/**
 * Build `lib/client.js` from `data/ru.json`.
 *
 * The DSH web client loads plugin bundles as `window.__ModuleLoader__.load({ id,
 * factory })` factories, so the language pack is emitted in that exact shape — no
 * bundler involved. Run: node tool/build-client.js
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')
const dataPath = path.join(root, 'data', 'ru.json')
const outPath = path.join(root, 'lib', 'client.js')

const ru = JSON.parse(fs.readFileSync(dataPath, 'utf8'))
const namespaces = Object.keys(ru).sort()
const total = namespaces.reduce((sum, ns) => sum + Object.keys(ru[ns]).length, 0)

const dictionaries = JSON.stringify(
  Object.fromEntries(namespaces.map((ns) => [ns, Object.fromEntries(Object.entries(ru[ns]).sort(([a], [b]) => a.localeCompare(b)))])),
  null,
  2,
).replace(/\n/g, '\n\t\t')

const banner = `/* Generated by tool/build-client.js — do not edit by hand.
 * ${namespaces.length} namespaces, ${total} Russian strings. */`

const source = `${banner}
window.__ModuleLoader__.load({
	id: "dsh-locale-ru",
	factory: (require) => {
		var module = { exports: {} };
		var exports = module.exports;
		Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
		/**
		 * Language definition offered in Settings → General. English supplies any key
		 * this pack does not translate yet, so partial coverage stays readable.
		 */
		const LANGUAGE = { id: "ru-RU", label: "Русский (полный)", fallback: "ru" };
		/** Russian dictionaries, one per client namespace. */
		const DICTIONARIES = ${dictionaries};
		/** Required client service: the locale registry. */
		const inject = ["locale"];
		/**
		 * Register the language and every dictionary as owned effects.
		 * @param ctx - Client root context.
		 */
		function apply(ctx) {
			ctx.effect(() => {
				try {
					return ctx.locale.addLanguage(LANGUAGE);
				} catch (error) {
					console.warn("[locale-ru] could not register the language", error);
				}
			}, "locale-ru: language");
			for (const [namespace, dictionary] of Object.entries(DICTIONARIES)) {
				ctx.effect(() => {
					try {
						return ctx.locale.register(namespace, "ru-RU", dictionary);
					} catch (error) {
						console.warn(\`[locale-ru] could not register \${namespace}\`, error);
					}
				}, \`locale-ru: \${namespace}\`);
			}
		}
		exports.apply = apply;
		exports.inject = inject;
		return module.exports;
	}
});
`

fs.writeFileSync(outPath, source)
console.log(`wrote ${path.relative(root, outPath)} — ${namespaces.length} namespaces, ${total} strings`)
